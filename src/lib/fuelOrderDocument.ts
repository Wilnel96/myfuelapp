export interface FuelOrderDocumentData {
  systemOrderNumber: string;
  clientOrderNumber: string | null;
  organizationName: string;
  vehicleLabel: string;
  garageLabel: string;
  fuelType: string;
  orderType: 'single' | 'multiple';
  litersOrdered: number;
  litersUsed: number;
  pricePerLiter: number;
  status: 'open' | 'fulfilled' | 'cancelled';
  createdAt: string;
}

const ORDER_TYPE_LABELS: Record<FuelOrderDocumentData['orderType'], string> = {
  single: 'Single refuel',
  multiple: 'Multiple refuel',
};

const STATUS_LABELS: Record<FuelOrderDocumentData['status'], string> = {
  open: 'Open',
  fulfilled: 'Fulfilled',
  cancelled: 'Cancelled',
};

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function fuelOrderDocumentTitle(order: Pick<FuelOrderDocumentData, 'systemOrderNumber' | 'clientOrderNumber'>): string {
  return `Fuel Order ${order.clientOrderNumber || order.systemOrderNumber}`;
}

export function buildFuelOrderHtml(order: FuelOrderDocumentData): string {
  const orderNumber = order.clientOrderNumber || order.systemOrderNumber;
  const remaining = Math.max(0, order.litersOrdered - order.litersUsed);
  const total = order.litersOrdered * order.pricePerLiter;
  const createdDate = new Date(order.createdAt).toLocaleDateString('en-ZA', { year: 'numeric', month: 'long', day: 'numeric' });
  const money = (value: number) => `R ${value.toFixed(2)}`;
  const litres = (value: number) => `${value.toFixed(2)} L`;

  const row = (label: string, value: string) => `
    <tr>
      <td style="padding:10px 0;border-bottom:1px solid #e5e7eb;color:#6b7280;font-size:14px;width:40%;">${escapeHtml(label)}</td>
      <td style="padding:10px 0;border-bottom:1px solid #e5e7eb;color:#111827;font-size:14px;font-weight:600;">${escapeHtml(value)}</td>
    </tr>`;

  const usageRows = order.orderType === 'multiple'
    ? row('Litres used', litres(order.litersUsed)) + row('Litres remaining', litres(remaining))
    : '';

  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${escapeHtml(fuelOrderDocumentTitle(order))}</title>
</head>
<body style="margin:0;padding:32px;background:#ffffff;font-family:Arial,Helvetica,sans-serif;color:#111827;">
  <div style="max-width:640px;margin:0 auto;">
    <div style="display:flex;justify-content:space-between;align-items:flex-start;border-bottom:2px solid #1d4ed8;padding-bottom:16px;">
      <div>
        <p style="margin:0;font-size:12px;letter-spacing:0.08em;text-transform:uppercase;color:#1d4ed8;font-weight:700;">Fuel Purchase Order</p>
        <h1 style="margin:4px 0 0;font-size:24px;color:#111827;">${escapeHtml(orderNumber)}</h1>
      </div>
      <div style="text-align:right;">
        <p style="margin:0;font-size:14px;font-weight:600;color:#111827;">${escapeHtml(order.organizationName)}</p>
        <p style="margin:4px 0 0;font-size:13px;color:#6b7280;">Issued ${escapeHtml(createdDate)}</p>
      </div>
    </div>

    ${order.clientOrderNumber ? `<p style="margin:16px 0 0;font-size:13px;color:#6b7280;">System order number: ${escapeHtml(order.systemOrderNumber)}</p>` : ''}

    <table role="presentation" style="width:100%;border-collapse:collapse;margin-top:24px;">
      ${row('Status', STATUS_LABELS[order.status])}
      ${row('Order type', ORDER_TYPE_LABELS[order.orderType])}
      ${row('Vehicle', order.vehicleLabel)}
      ${row('Garage', order.garageLabel)}
      ${row('Fuel type', order.fuelType)}
      ${row('Litres ordered', litres(order.litersOrdered))}
      ${usageRows}
      ${row('Price per litre', money(order.pricePerLiter))}
      ${row('Estimated total', money(total))}
    </table>

    <p style="margin:24px 0 0;font-size:12px;color:#6b7280;line-height:1.5;">
      Present this order at the garage when refuelling. The order applies only at the garage listed above and at the price shown.
    </p>
    <p style="margin:32px 0 0;font-size:11px;color:#9ca3af;">Generated by MyFuelApp.net</p>
  </div>
</body>
</html>`;
}
