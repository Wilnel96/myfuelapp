import jsPDF from 'jspdf';

export interface FuelOrderPdfData {
  systemOrderNumber: string;
  clientOrderNumber: string | null;
  organizationName: string;
  vehicleLabel: string;
  garageLabel: string;
  fuelType: string;
  orderType: 'single' | 'multiple';
  litersOrdered: number;
  litersUsed: number;
  pricePerLiter: number;
  status: 'open' | 'fulfilled' | 'cancelled';
  createdAt: string;
}

const ORDER_TYPE_LABELS: Record<FuelOrderPdfData['orderType'], string> = {
  single: 'Single refuel',
  multiple: 'Multiple refuel',
};

const STATUS_LABELS: Record<FuelOrderPdfData['status'], string> = {
  open: 'Open',
  fulfilled: 'Fulfilled',
  cancelled: 'Cancelled',
};

const MARGIN = 20;
const LABEL_WIDTH = 55;

export function fuelOrderNumber(order: Pick<FuelOrderPdfData, 'systemOrderNumber' | 'clientOrderNumber'>): string {
  return order.clientOrderNumber || order.systemOrderNumber;
}

export function fuelOrderSubject(order: FuelOrderPdfData): string {
  return `Fuel Order ${fuelOrderNumber(order)}`;
}

export function fuelOrderFilename(order: FuelOrderPdfData): string {
  const safe = fuelOrderNumber(order).replace(/[^a-zA-Z0-9_-]/g, '_');
  return `Fuel_Order_${safe}.pdf`;
}

export function buildFuelOrderPdf(order: FuelOrderPdfData): jsPDF {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const right = pageWidth - MARGIN;
  const valueX = MARGIN + LABEL_WIDTH;
  const valueWidth = right - valueX;
  const remaining = Math.max(0, order.litersOrdered - order.litersUsed);
  const total = order.litersOrdered * order.pricePerLiter;
  const issued = new Date(order.createdAt).toLocaleDateString('en-ZA', { year: 'numeric', month: 'long', day: 'numeric' });
  const money = (value: number) => `R ${value.toFixed(2)}`;
  const litres = (value: number) => `${value.toFixed(2)} L`;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(29, 78, 216);
  doc.text('FUEL PURCHASE ORDER', MARGIN, 24);

  doc.setFontSize(20);
  doc.setTextColor(17, 24, 39);
  doc.text(fuelOrderNumber(order), MARGIN, 35);

  doc.setFontSize(11);
  doc.text(order.organizationName || '', right, 24, { align: 'right' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(107, 114, 128);
  doc.text(`Issued ${issued}`, right, 31, { align: 'right' });
  if (order.clientOrderNumber) {
    doc.text(`System order number: ${order.systemOrderNumber}`, MARGIN, 42);
  }

  doc.setDrawColor(29, 78, 216);
  doc.setLineWidth(0.6);
  doc.line(MARGIN, 47, right, 47);

  const rows: [string, string][] = [
    ['Status', STATUS_LABELS[order.status]],
    ['Order type', ORDER_TYPE_LABELS[order.orderType]],
    ['Vehicle', order.vehicleLabel],
    ['Garage', order.garageLabel],
    ['Fuel type', order.fuelType],
    ['Litres ordered', litres(order.litersOrdered)],
  ];
  if (order.orderType === 'multiple') {
    rows.push(['Litres used', litres(order.litersUsed)], ['Litres remaining', litres(remaining)]);
  }
  rows.push(['Price per litre', money(order.pricePerLiter)], ['Estimated total', money(total)]);

  let y = 58;
  rows.forEach(([label, value]) => {
    const lines = doc.splitTextToSize(value, valueWidth) as string[];
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(107, 114, 128);
    doc.text(label, MARGIN, y);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(17, 24, 39);
    doc.text(lines, valueX, y);
    const rowHeight = lines.length * 5 + 4;
    doc.setDrawColor(229, 231, 235);
    doc.setLineWidth(0.2);
    doc.line(MARGIN, y + rowHeight - 3, right, y + rowHeight - 3);
    y += rowHeight + 3;
  });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(107, 114, 128);
  const note = doc.splitTextToSize(
    'Present this order at the garage when refuelling. The order applies only at the garage listed above and at the price shown.',
    right - MARGIN,
  ) as string[];
  doc.text(note, MARGIN, y + 8);

  doc.setTextColor(156, 163, 175);
  doc.setFontSize(8);
  doc.text('Generated by MyFuelApp.net', MARGIN, 285);

  return doc;
}

export function fuelOrderPdfBase64(doc: jsPDF): string {
  const bytes = new Uint8Array(doc.output('arraybuffer'));
  let binary = '';
  const chunkSize = 0x8000;
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunkSize));
  }
  return btoa(binary);
}
